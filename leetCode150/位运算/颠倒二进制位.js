// 颠倒给定的 32 位无符号整数的二进制位。
// 提示：输入是 32 位无符号整数，JavaScript 中需注意位运算按 32 位有符号处理，结果需用 >>> 0 转回无符号。

// 思路：逐位取出再拼接
// 循环 32 次：把 result 左移一位空出末位，取出 n 的末位填进去，n 逻辑右移一位。
// 最后 result >>> 0 把符号位还原为无符号整数。

var reverseBits = function (n) {
  let result = 0
  for (let i = 0; i < 32; i++) {
    result = (result << 1) | (n & 1)
    n >>>= 1
  }
  return result >>> 0
}

console.log(reverseBits(43261596)) // 964176192
// 43261596 = 00000010100101000001111010011100
// 反转后   = 00111001011110000010100101000000 = 964176192
console.log(reverseBits(4294967293)) // 3221225471
